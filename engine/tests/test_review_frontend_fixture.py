"""The #290 review screens' fixture: the review service's own answers for #289's example.

`engine/examples/human-review/contract.json` holds the context at r1 and the save that
makes r2. The screens also show a version before and after a save, so
`apps/desktop/src/fixtures/human-review-revisions.json` holds the refresh at r1 and the
context at r2, from the same model, workspace double, principal and save request. It must
equal the service's answers; TMODEL_UPDATE_FIXTURES=1 rewrites it after a contract change
agreed on #289 and #290. The Review id is fixed to the contract's, as the contract fixes it.
"""

import json
import os
from pathlib import Path

import yaml
from review_support import PRINCIPAL, MemoryWorkspace

from engine import review_service
from engine.review_service import ReviewService

ROOT = Path(__file__).resolve().parents[2]
EXAMPLES = ROOT / "engine" / "examples" / "human-review"
GUI_FIXTURE = ROOT / "apps" / "desktop" / "src" / "fixtures" / "human-review-revisions.json"
NOTE = (
    "Generated by engine/tests/test_review_frontend_fixture.py from "
    "engine/examples/human-review: synthetic test judgments, not human acceptance."
)


def test_gui_fixture_is_the_review_services_answer(monkeypatch):
    contract = json.loads((EXAMPLES / "contract.json").read_text(encoding="utf-8"))
    workspace = MemoryWorkspace(
        yaml.safe_load((EXAMPLES / "model.yaml").read_text(encoding="utf-8"))
    )
    service = ReviewService(workspace)
    monkeypatch.setattr(review_service, "uuid4", lambda: "fixture-review")
    refresh = {"model_id": "local:one", "revision": "r1", "matrix": "annex-h-table-h8"}
    payload = {
        "note": NOTE,
        "refresh_r1": {"request": refresh, "response": service.refresh_model(refresh, PRINCIPAL)},
    }
    saved = service.save_model_changes(contract["save"]["request"], PRINCIPAL)
    assert saved == contract["save"]["response"]
    context = {**contract["context"]["request"], "revision": "r2"}
    payload["context_r2"] = {
        "request": context,
        "response": service.get_review_context(context, PRINCIPAL),
    }
    if os.environ.get("TMODEL_UPDATE_FIXTURES") == "1":
        text = json.dumps(payload, indent=1, ensure_ascii=False) + "\n"
        GUI_FIXTURE.write_text(text, encoding="utf-8")
    assert json.loads(GUI_FIXTURE.read_text(encoding="utf-8")) == payload, (
        "the review answers changed: agree the new shape on #289 and #290, then regenerate "
        "the fixture with TMODEL_UPDATE_FIXTURES=1 pytest tests/test_review_frontend_fixture.py"
    )
